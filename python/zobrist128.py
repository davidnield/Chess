# python-chess's own hasher over the high halves: the piece, castling, en-passant and turn
# rules are then upstream's, exactly as for the low half.
_HASHER_HI = chess.polyglot.ZobristHasher(HI_KEYS)


def zobrist_hi_int64(board: chess.Board) -> int:
    """The high half of the 128-bit key, as a signed int64."""
    h = _HASHER_HI(board)
    return h - INT64_RANGE if h > INT64_MAX else h


def zobrist128(board: chess.Board) -> tuple[int, int]:
    """(lo, hi): lo is zobrist_int64(board)."""
    return zobrist_int64(board), zobrist_hi_int64(board)
